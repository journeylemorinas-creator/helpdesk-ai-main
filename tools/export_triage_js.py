"""Export the triage rules from triage.py to a JavaScript file.

    python tools/export_triage_js.py path/to/triage-data.js

The portfolio website uses this so visitors can try the same rules in the
browser (GitHub Pages cannot run Flask). Run it again whenever triage.py changes.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import triage  # noqa: E402

data = {
    "KEYWORDS": triage.KEYWORDS,
    "CRITICAL_WORDS": triage.CRITICAL_WORDS,
    "HIGH_WORDS": triage.HIGH_WORDS,
    "LOW_WORDS": triage.LOW_WORDS,
    "SUGGESTIONS": triage.SUGGESTIONS,
    "TIE_ORDER": ["Security", "Network", "Hardware", "Software", "Account", "General"],
}

out = sys.argv[1] if len(sys.argv) > 1 else "triage-data.js"
with open(out, "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/export_triage_js.py from triage.py. Do not edit by hand. */\n")
    f.write("window.TRIAGE_DATA = " + json.dumps(data, indent=2, ensure_ascii=False) + ";\n")
print("wrote", out)
